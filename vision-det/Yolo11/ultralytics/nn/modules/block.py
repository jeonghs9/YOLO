def _best_factor(ch: int, prefer: int) -> int:
    for f in range(prefer, 0, -1):
        if ch % f == 0:
            return f
    return 1

class Bottleneck_EMA(nn.Module):
    """Bottleneck + EMA attention wrapper."""
    def __init__(self, c1, c2, shortcut=True, g=1, k=(3, 3), e=1.0, ema_groups=8):
        super().__init__()
        # Bottleneck k 형태는 레포 구현에 따라 다를 수 있어, 우선 기존 그대로 두되
        self.block = Bottleneck(
            c1, c2, shortcut=shortcut, g=g,
            k=(k, k) if isinstance(k, int) else k,
            e=e
        )

        f = _best_factor(c2, ema_groups)
        self.attn = EMA(c2, factor=f)  

    def forward(self, x):
        return self.attn(self.block(x))

class C3_EMA(nn.Module):
    """CSP Bottleneck with 3 convolutions + Bottleneck_EMA blocks."""
    def __init__(self, c1, c2, n=1, shortcut=True, g=1, e=0.5, ema_groups=8):
        super().__init__()
        c_ = int(c2 * e)
        self.cv1 = Conv(c1, c_, 1, 1)
        self.cv2 = Conv(c1, c_, 1, 1)
        self.cv3 = Conv(2 * c_, c2, 1, 1)
        self.m = nn.Sequential(*(
            Bottleneck_EMA(c_, c_, shortcut=shortcut, g=g, k=(3, 3), e=1.0, ema_groups=ema_groups)
            for _ in range(n)
        ))

    def forward(self, x):
        return self.cv3(torch.cat((self.m(self.cv1(x)), self.cv2(x)), 1))



