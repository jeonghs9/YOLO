class EMA(nn.Module):
    """
    Efficient Multi-Scale Attention (EMA) module with cross-spatial learning.

    Key ideas (paper-consistent):
      1) Channel grouping: split C into G groups, process as (B*G, C/G, H, W)
      2) Parallel branches:
         - 1x1 branch with two routes: encode H- and W-direction context via 1D global average pooling
         - 3x3 branch: capture local/multi-scale spatial information
      3) Cross-spatial learning: use matmul between pooled channel descriptors and flattened spatial features
         to produce a spatial attention map, then reweight input.

    Args:
      channels (int): input channel C
      factor (int): number of groups G (default 8; must divide channels)
    """
    def __init__(self, channels: int, factor: int = 8):
        super().__init__()
        if channels % factor != 0:
            raise ValueError(f"EMA: channels({channels}) must be divisible by factor/groups({factor}).")

        self.channels = channels
        self.groups = factor #특징그룹화를 사용하여 특징맵 X를 G개의 하위 특징으로 분할하기 위해 특징 그룹화를 사용
        cg = channels // factor  # 각 그룹에서 특정 유형의 정보를 전문적으로 추출하고 학습할 수 있게 된다

        # 1x1 branch: after concat([x_h, x_w]) along "height" axis, fuse by 1x1 conv
        self.conv1x1 = nn.Conv2d(cg, cg, kernel_size=1, stride=1, padding=0, bias=True) #1x1 브랜치에서 1x1 컨볼루션 레이어가 적용되어 채널 무결성을 유지하고 교차 채널 상호작용을 포착
        # -> 전역정보를 나타내는 두개의 인코딩된 특징 벡터를 생성하며 높이 방향을 따라 연결됨
        # 1x1 브랜치에서 각 경로는 수평 및 수직 공간 방향을 따라 채널 정보를 인코딩하기 위해 1D 전역 평균 풀링을 사용
        # 연결된 출력에는 채널 무결성을 유지하고 다른 채널 간의 정보를 혼합하여 채널간 상호작용을 포착하기위해 1x1 컨볼루션이 적용
        # 출력은 두 개의 벡터로 분할되고 2D 이항 분포에서 주의 가중치를 조정하기 위해 비선형 시그모이드 함수를 사용하여 정제됨
        # 채널별 주의 맵은 그룹 내 곱셈을 통해 결합되어 채널 간의 상호작용 특징을 향상 시킴

        # 3x3 branch: local spatial modeling
        self.conv3x3 = nn.Conv2d(cg, cg, kernel_size=3, stride=1, padding=1, bias=True)
        # -> 다중 스케일 종간 정보를 포착하기 위해 3x3 컨볼루션 커널을 가진 단일 경로 사용
        # 1x1 브랜치의 출력은 전역 공간 정보를 인코딩하기 위해 2D 전역 평균 풀링을 거침
        # 풀링된 출력은 3x3 브랜치의 변환된 출력돠 통합되어 두 공간 정보 소스를 통해 특징 집계를 향상시키기 위해 차원을 정렬

        #

        # Normalize grouped feature (GroupNorm over channels per group)
        self.gn = nn.GroupNorm(num_groups=1, num_channels=cg)

        # Global pooling for channel descriptor
        self.agp = nn.AdaptiveAvgPool2d(1)


        # Softmax for cross-spatial learning
        self.softmax = nn.Softmax(dim=-1)

        self.sigmoid = nn.Sigmoid()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x: (B, C, H, W)
        return: (B, C, H, W)
        """
        b, c, h, w = x.shape #배치(B), 채널(C), 높이(H), 너비(W)
        g = self.groups
        cg = c // g # 그룹당 채널 수

        # (B, C, H, W) -> (B*G, C/G, H, W)
        xg = x.view(b * g, cg, h, w) #(B*G, C/G, H, W) 형태로 변환), 입력 특징 맵 X를 채널 차원에 따라 G개의 하위 특징으로 분할한다, C/G 크기의 채널 그룹이 마치 별개의 항목처럼 처리되어 이후 연산들이 그룹별로 독립적으로 수행

        # ----- 1x1 branch with two routes (H and W direction) -----
        # Encode along width: mean over W -> (B*G, cg, H, 1)
        x_h = xg.mean(dim=3, keepdim=True)  # 각 그룹 특징맵 (xg)에서 너비(W)방향으로 평균을 계싼하여 높이(H) 방향의 컨텍스트 정보를 인코딩 (결과:BG, cg, H, 1)

        # Encode along height: mean over H -> (B*G, cg, 1, W) then permute -> (B*G, cg, W, 1)
        x_w = xg.mean(dim=2, keepdim=True).permute(0, 1, 3, 2) # 각 그룹 특징맵 (xg)에서 높이(H) 방향으로 평균을 계산하여 너비(W) 방향의 컨텍스트 정보를 인코딩 (결과: (B*G, cg, 1, W)) 그런 다음 차원을 바꿔 (B*G, cg, W, 1) 형태로 변환

        # -> 1X1 브랜치에서 1D 전역 평균 풀링을 사용하여 채널 정보를 가로세로 공간 방향으로 인코딩 (각 한줄씩마다 평균 풀링 진행)

        # Concat along "height-like" axis (dim=2): (H+W, 1)
        y = torch.cat([x_h, x_w], dim=2)  # (B*G, cg, H+W, 1) # H 방향과 W 방향으로 인코딩된 컨텍스트를 높이 2 차원을 따라 결합

        # Fuse by 1x1 conv
        y = self.conv1x1(y) # 결합된 y에 1x1 컨볼루션을 적용하여 H와 W 정보가 섞인 특징 맵 내에서 채널간의 상호작용을 포착

        # -> 전역 정보를 나타내는 두 개의 인코딩된 특징 벡터를 생성하며 이들은 높이 방향으로 연결됨 이후 1x1 컨볼루션 레이거가 적용되어 채널 무결성을 유지하고 교차 채널 상호작용을 포착

        # Split back to H and W parts
        y_h, y_w = torch.split(y, [h, w], dim=2)  # y_h: (B*G,cg,H,1), y_w: (B*G,cg,W,1) # 융합된 y를 원래 H와 W 부분으로 나눔

        # Restore y_w to (B*G, cg, 1, W)
        y_w = y_w.permute(0, 1, 3, 2) # y_w의 차원 순서를 복원하여 (B*G, cg, 1, W) 형태로 변환

        # Sigmoid gates (binomial-like gating in the description)
        a_h = self.sigmoid(y_h) #각각 H와 W 방향의 특징에 시그모이드 함수를 적용하여 어텐션 가중치를 생성, 0~1사이 값으로 각공간 위치의 중요도를 나타냄
        a_w = self.sigmoid(y_w)

        # -> 출력은 두 개의 벡터로 분할되고 비선형 시그모이드 함수를 사용하여 정제됨

        # Apply channel-wise interactive reweighting inside each group
        x1 = self.gn(xg * a_h * a_w) # 원본 그룹 특징 맵 xg에 H와 W 방향의 어텐션 가중치(a_h, a_w)를 곱하여 채널별 상호작용 특징을 향상시킴, "각 그룹 내에서 곱셈을 통해 채널별 어텐션 맵을 결합하여 상호작용 특징을 강화", GN을 통해 정규화하여 특징 안정

        # ----- 3x3 branch -----
        x2 = self.conv3x3(xg) # 원본 그룹 특징 맵 xg에 3x3 컨볼루션을 적용

        # ----- Cross-spatial learning (pixel-level pairwise relationships) -----
        # Channel descriptors (B*G, cg, 1, 1) -> (B*G, 1, cg)
        d1 = self.agp(x1).view(b * g, 1, cg) #1x1 브랜치 출력에서 2D 전역 평균풀링을 통해 각 그룹의 채널별 특징 기술자를 추출하고 (B*G, 1, cg) 형태로 변환
        d2 = self.agp(x2).view(b * g, 1, cg) #3x3 브랜치에서도 동일하게 채널 기술자를 추출

        # Softmax over channels to form distributions
        s1 = self.softmax(d1)  # (B*G, 1, cg) #추출된 채널 기술자에 소프트맥스를 적용하여 확률 분포 형태의 가중치 s1, s2를 만듦
        s2 = self.softmax(d2)  # (B*G, 1, cg)

        # Flatten spatial: (B*G, cg, H*W)
        f1 = x1.view(b * g, cg, h * w) # x1의 공간차원(H, W)을 평탄화하여 (B*G, cg, H*W) 형태로 변환
        f2 = x2.view(b * g, cg, h * w)

        # Matrix dot products -> (B*G, 1, H*W)
        # Two attention maps aggregated (global+local reciprocal interaction)
        att = torch.matmul(s1, f2) + torch.matmul(s2, f1) # "교차 공간 학습"의 핵심. s1(1x1 브랜치의 채널 중요도)와 f2(3x3 브랜치의 평탄화된 공간 특징)을 곱하고, s2 (3x3 브랜치 채널 중요도)외 f1(1x1 브랜치의 평탄화된 공간 특징)을 곱한 다음 이들을 더함
        att = att.view(b * g, 1, h, w) # 계산된 att를 원래의 (B*G, 1, H, W) 형태의 어텐션 맵으로 재구성

        # Final spatial weights
        w_spatial = self.sigmoid(att) # 최종 att 맵에 시그모이드를 적용하여 공간 어텐션 가중치 w_spatial을 생성

        # Reweight original grouped feature and restore shape
        out = (xg * w_spatial).view(b, c, h, w) # 원본 그룹 특징 맵 xg에 최종적으로 계산된 공간 어텐션 가중치 w_spatial을 곱하여 특징을 재가중치
        return out # 최종 출력은 원래 형태 (B, C, H, W)로 복원되어 반환


class C2f_EMA(nn.Module):
    """Faster Implementation of CSP Bottleneck with 2 convolutions and embedded EMA."""

    def __init__(self, c1, c2, n=1, shortcut=False, g=1, e=0.5):
        """Initialize CSP bottleneck layer with two convolutions with arguments ch_in, ch_out, number, shortcut, groups,
        expansion.
        """
        super().__init__()
        self.c = int(c2 * e)  # hidden channels
        self.cv1 = Conv(c1, 2 * self.c, 1, 1)
        self.cv2 = Conv((2 + n) * self.c, c2, 1)
        self.m = nn.ModuleList(Bottleneck(self.c, self.c, shortcut, g, k=((3, 3), (3, 3)), e=1.0) for _ in range(n))
        self.ema = EMA(self.c)  # Embedded EMA in the second bottleneck

    def forward(self, x):
        """Forward pass through C2f layer with embedded EMA."""
        y = list(self.cv1(x).chunk(2, 1))
        for i, m in enumerate(self.m):
            if i == 1:  # Apply EMA to the second bottleneck
                y.append(self.ema(m(y[-1])))
            else:
                y.append(m(y[-1]))
        return self.cv2(torch.cat(y, 1))

    def forward_split(self, x):
        """Forward pass using split() instead of chunk()."""
        y = list(self.cv1(x).split((self.c, self.c), 1))
        for i, m in enumerate(self.m):
            if i == 1:  # Apply EMA to the second bottleneck
                y.append(self.ema(m(y[-1])))
            else:
                y.append(m(y[-1]))
        return self.cv2(torch.cat(y, 1))


